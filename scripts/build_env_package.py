def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output-dir",
        type=Path,
        required=True,
        help="where the archive, its .sha256 sidecar and index.json are written",
    )
    parser.add_argument(
        "--work-dir",
        type=Path,
        help="scratch space (default: a temporary directory, removed afterwards)",
    )
    parser.add_argument(
        "--revision",
        default="HEAD",
        help="the commit to read this repository's inputs from (default: HEAD)",
    )
    parser.add_argument(
        "--repo",
        type=Path,
        default=REPO_ROOT,
        help="the checkout to read the revision from (default: this repository)",
    )
    parser.add_argument("kind", choices=("workspace", "tools"), help="which package to build")
    parser.add_argument(
        "--arch",
        default=os.uname().machine.replace("x86_64", "amd64").replace("aarch64", "arm64"),
        help="the tools package's architecture (default: this machine's)",
    )
    parser.add_argument("--os", dest="os_name", default="linux", help="the tools package's OS")
    parser.add_argument(
        "--packager-image",
        help=(
            "run the environment-specific steps in this image instead of the pinned "
            "packager (containers/build-environment-packager/); for publishing that "
            "image the first time and for trying a change to it"
        ),
    )
    parser.add_argument(
        "--version-suffix",
        help="append a PEP 440 local segment to the declared version, as in "
        "ci.<sha> for a per-commit build — a local version is the one shape "
        "a package host will not publish",
    )
    arguments = parser.parse_args(argv)

    # Asked for before anything is fetched or cloned: an unpinned packager
    # is a refusal, and a refusal is worth nothing after twenty minutes of
    # work.
    image = packager_image(arguments.packager_image)

    work = arguments.work_dir
    temporary = None
    if work is None:
        temporary = tempfile.TemporaryDirectory(prefix="mcuhome-env-package-")
        work = Path(temporary.name)
    work.mkdir(parents=True, exist_ok=True)

    try:
        if arguments.kind == "workspace":
            package = build_workspace_package(
                repository=arguments.repo,
                revision=arguments.revision,
                output_dir=arguments.output_dir,
                work=work,
                image=image,
                version_suffix=arguments.version_suffix,
            )
        else:
            package = build_tools_package(
                repository=arguments.repo,
                revision=arguments.revision,
                output_dir=arguments.output_dir,
                work=work,
                arch=arguments.arch,
                os_name=arguments.os_name,
                image=image,
                version_suffix=arguments.version_suffix,
            )
    finally:
        if temporary is not None:
            temporary.cleanup()

    print(f"{package.path.name}  {package.sha256}  {package.size} bytes")
    return 0


if __name__ == "__main__":  # pragma: no cover - the command line's entry point
    raise SystemExit(main(sys.argv[1:]))
