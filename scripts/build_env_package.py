# Downloads
# --------------------------------------------------------------------------


def fetch(url: str, sha256: str, cache: Path) -> Path:
    """Download *url* into *cache* unless it is already there, and verify it.

    The hash is the whole point: a package that silently absorbs a re-tagged
    upstream artifact is not a reproducible build environment. A cached file
    is verified again rather than trusted, so a truncated download from an
    earlier run cannot survive into a package.
    """
    cache.mkdir(parents=True, exist_ok=True)
    target = cache / sha256
    if not target.exists():
        print(f"  fetching {url}", flush=True)
        with urllib.request.urlopen(url) as response, open(target, "wb") as handle:
            shutil.copyfileobj(response, handle)
    digest = hashlib.sha256()
    with open(target, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    if digest.hexdigest() != sha256:
        target.unlink()
        raise SystemExit(f"{url} is not the pinned artifact: {digest.hexdigest()} != {sha256}")
    return target


