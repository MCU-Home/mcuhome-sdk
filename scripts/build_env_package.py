"""Build MCUHome's two build-environment packages — the same bytes every time.

The build environment specification
(``docs/spec/build-environment-specification.md``, generation 3) defines a
build environment as a *package set* rather than as an image, and
``docs/design/build-environment.md`` names MCUHome's set:

``mcuhome-build-workspace``
    Architecture-neutral. The materialized west workspace at the revisions
    ``west.yml`` pins, with ``patches/`` applied, the Espressif HAL blobs
    fetched, the west configuration pre-populated, the record of what was
    resolved, the pre-generated Matter data-model code, and the
    environment's self-description (specification §5).

``mcuhome-build-tools_<os>-<arch>``
    One per platform. Zephyr SDK toolchain, CMake, Ninja, gn, the complete
    wheel set the build virtual environment is created from, and the entry
    point.

One script for both kinds, because the half that must not drift is shared:
the deterministic archive writer, the file names, the sidecars and the
index. Two scripts would be two implementations of one byte-level contract.

Each package is published with its **meta file** — ``meta.json`` at the top
of the archive and ``<archive>.meta.json`` beside it, the same bytes twice.
It is the only document that travels beside an archive besides the
``.sha256``.
It states what the package is, which version of the next stage it requires
(the workspace requires tools; the tools require nothing), the hash of its
own inputs, and what it resolved to: the west projects and patches for the
workspace, the tool versions for the tools. The versions themselves come
from ``packaging/build-environment/environment.json`` at the packaged
commit — the workspace and the tools are release lines of their own, and
neither takes the SDK's version.

**Why the bytes have to be reproducible.** A build context pins packages by
hash, and every delivery of a package set — an image above all — states a
hash for every member (specification §5.1). Two parties building the same
revision must therefore reach the same digest, or the second one's package
can never satisfy a pin the first one resolved. Everything below that looks
fussy is that requirement, and it is the approach ``scripts/build_sdk_archive.py``
already uses for the SDK package: PAX format, members sorted by name, one
mtime for the whole archive, ``uid``/``gid`` 0 with empty
``uname``/``gname``, modes narrowed to two values, one fixed zstd level,
single-threaded compression.

Two differences to the SDK archive, both forced by the size of these
payloads (gigabytes rather than megabytes):

* the archive is *streamed* — tar into zstd into the output file — instead
  of being assembled in memory;
* the zstd level is 10 rather than 19. Level 19 on a multi-gigabyte
  workspace costs hours for a few per cent; the level is fixed either way,
  which is all determinism asks of it.

**What the source of truth is.** ``west.yml``, ``patches/`` and the Matter
ZAP inputs are read out of a *commit* with ``git archive``, never out of the
working tree — the same rule the SDK archive follows, for the same reason:
an uncommitted edit must not be able to reach a package. The tool downloads
are pinned by version and SHA-256 below.

Usage::

    build_env_package.py workspace --output-dir <dir> [--revision <rev>]
    build_env_package.py tools     --output-dir <dir> [--arch amd64]

Both take ``--version-suffix ci.<sha>`` to build a per-commit package: the
declared version plus a PEP 440 local segment, which is the one shape a
package host will not publish.

Both subcommands do their environment-specific work inside a pinned
container, because neither can be done correctly on an arbitrary host: the
workspace is laid out by the exact ``west`` that will later read it and its
Matter code is generated by the exact ``zap`` the pinned CHIP names, and
the wheel set has to be built by the interpreter of the base image the
environment runs on. The host contributes the downloads, the packing and
nothing else.

Exit status: 0 on success, 2 on a usage error; a failing child command
propagates as a ``CalledProcessError``.
"""

