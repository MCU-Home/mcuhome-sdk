@dataclass(frozen=True)
class Package:
    """One built package: the file, and everything the index says about it."""

    path: Path
    name: str
    version: str
    sha256: str
    size: int


def _members(root: Path) -> list[tuple[str, Path]]:
    """Every member of *root* as ``(archive name, path)``, sorted by byte order.

    Sorted on the encoded name rather than on the string, because the archive
    order has to be a property of the bytes and not of a locale. Directories
    are emitted too — including empty ones, which a package can carry and
    ``git archive`` could not (the SDK mount point is exactly one).
    """
    found: list[tuple[bytes, str, Path]] = []
    for path in root.rglob("*"):
        name = path.relative_to(root).as_posix()
        found.append((name.encode("utf-8"), name, path))
    found.sort(key=lambda item: item[0])
    return [(name, path) for _, name, path in found]


def write_archive(root: Path, target: Path, *, mtime: int) -> tuple[str, int]:
    """Pack *root* into *target* as a deterministic ``.tar.zst``; digest and size.

    PAX rather than GNU: it is the POSIX-2001 format with a defined answer
    for everything an extractor might meet, and Python's writer emits an
    extended header only for a field that does not fit — with an integer
    *mtime*, ``uid``/``gid`` 0 and no path over 100 bytes, that is none of
    them here.

    Modes are narrowed to 0755 and 0644. The exec bit is the one mode fact a
    consumer reads — a toolchain full of compilers, ``gn``, ``ninja`` and the
    entry point are all spawned as children — and everything else a
    filesystem's umask happens to carry is noise that would change the
    digest.

    Streamed rather than assembled: tar writes into the zstd compressor,
    which writes into the file, and the digest is taken on the way past. A
    workspace package is several gigabytes and does not fit anywhere else.
    """
    digest = hashlib.sha256()
    size = 0

    class _Tap(io.RawIOBase):
        """The output file, hashed and counted as it is written."""

        def __init__(self, handle: io.BufferedWriter) -> None:
            self._handle = handle

        def writable(self) -> bool:
            return True

        def write(self, data) -> int:  # noqa: ANN001 - a buffer protocol object
            nonlocal size
            chunk = bytes(data)
            digest.update(chunk)
            size += len(chunk)
            self._handle.write(chunk)
            return len(chunk)

    # threads=0 because a multi-threaded compressor splits the input into
    # jobs and produces different bytes for the same input. The checksum is
    # off and the content size is off as well: in a streaming frame the
    # length is not known when the header is written, so leaving it out is
    # the one answer that does not depend on which API knew what.
    compressor = zstandard.ZstdCompressor(
        level=ZSTD_LEVEL,
        write_checksum=False,
        write_content_size=False,
        threads=0,
    )

    target.parent.mkdir(parents=True, exist_ok=True)
    with open(target, "wb") as handle:
        tap = io.BufferedWriter(_Tap(handle))
        writer = compressor.stream_writer(tap, closefd=False)
        with writer, tarfile.open(fileobj=writer, mode="w|", format=tarfile.PAX_FORMAT) as tar:
            _add_members(tar, root, mtime=mtime)
        tap.flush()
    return digest.hexdigest(), size


def _add_members(tar: tarfile.TarFile, root: Path, *, mtime: int) -> None:
    """Every member of *root*, normalized to the fields a package may carry."""
    for name, path in _members(root):
        info = tarfile.TarInfo(name)
        info.mtime = mtime
        info.uid = 0
        info.gid = 0
        info.uname = ""
        info.gname = ""
        if path.is_symlink():
            info.type = tarfile.SYMTYPE
            info.mode = 0o777
            info.linkname = os.readlink(path)
            tar.addfile(info)
        elif path.is_dir():
            info.type = tarfile.DIRTYPE
            info.mode = 0o755
            tar.addfile(info)
        elif path.is_file():
            info.type = tarfile.REGTYPE
            info.mode = 0o755 if path.stat().st_mode & 0o111 else 0o644
            info.size = path.stat().st_size
            with open(path, "rb") as content:
                tar.addfile(info, content)
        else:
            raise SystemExit(
                f"{path} is neither a regular file, a directory nor a symbolic "
                "link — a package carries nothing else"
            )


def tools_package_name(os_name: str, arch: str) -> str:
    """The concrete tools package of one platform: ``<family>_<os>-<arch>``.

    ``_`` and not another ``-``: a package name is otherwise lowercase
    alphanumerics and ``-``, so the first ``_`` is the one character that
    splits the family from the platform without anybody having to know the
    family's name first (specification §5.1).
    """
    return f"{TOOLS_FAMILY}_{os_name}-{arch}"


def package_filename(name: str, version: str) -> str:
    """``<name>-<version>.tar.zst`` — the file-name scheme for every package.

    *name* is the full package name, architecture suffix included, so the
    tools package of one platform is
    ``mcuhome-build-tools_linux-amd64-<version>.tar.zst``.
    """
    return f"{name}-{version}.tar.zst"


def sidecar_entry(path: Path) -> dict:
    """One sidecar as an index entry: which file, which bytes, how many.

    The same three fields the archive's own entry carries, because the
    question is the same one — a reader that has the index has everything
    it needs to fetch the file and check it before trusting a word of it.
    """
    payload = path.read_bytes()
    return {
        "file": path.name,
        "sha256": hashlib.sha256(payload).hexdigest(),
        "size": len(payload),
    }


def write_index(
    path: Path,
    *,
    package: str,
    version: str,
    file: str,
    sha256: str,
    size: int,
    meta_file: dict | None = None,
):
    """Record this package in the static index, keeping the versions already there.

    The index answers exactly one question — "which file, and which bytes,
    for ``(name, version)``". A URL here would be a second, weaker answer to
    a question the operator's source list already answers. An existing index
    is read and extended rather than replaced; an unreadable one is a
    refusal, never an overwrite, because it is the only record of the
    packages already in that directory.

    ``meta_file`` records the meta sidecar the same way, under the name the
    package registry's index uses for it — so whoever resolves a release
    chain finds it identically in an operator's directory and on a host.
    The key is ``meta_file`` and not ``meta`` because ``meta`` already means
    something else in that index: it is the member that makes an entry a
    *meta package*, the family that maps platforms onto concrete packages.
    """
    document: dict = {"packages": {}}
    if path.exists():
        try:
            found = json.loads(path.read_text(encoding="utf-8"))
        except ValueError as failure:
            raise SystemExit(f"{path} is not readable as JSON: {failure}") from failure
        if not isinstance(found, dict) or not isinstance(found.get("packages"), dict):
            raise SystemExit(f"{path} is not an index: no packages object")
        document = found
    entry: dict = {"file": file, "sha256": sha256, "size": size}
    if meta_file is not None:
        entry["meta_file"] = meta_file
    document["packages"].setdefault(package, {})[version] = entry
    path.write_text(
        json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def publish(
    root: Path, output_dir: Path, *, name: str, version: str, mtime: int, meta: bytes
) -> Package:
    """Pack *root*, write the sidecars and the index, and say what came out.

    *meta* is written on both sides of the archive from this one value —
    at the top of the tree before it is packed, and beside the archive
    afterwards — so the copy a reader happens to take cannot decide what
    the package is. Inside, because an unpacked store entry has to be able
    to say what it is with nothing else present; beside, because whoever
    resolves a release chain reads what a package requires before it
    fetches a gigabyte of it.
    """
    (root / release_lines.META_FILE).write_bytes(meta)
    output_dir.mkdir(parents=True, exist_ok=True)
    archive = output_dir / package_filename(name, version)
    digest, size = write_archive(root, archive, mtime=mtime)
    sidecar = output_dir / f"{archive.name}{release_lines.META_SUFFIX}"
    sidecar.write_bytes(meta)
    # sha256sum's own format — bare hex, two spaces, the file name — so
    # `sha256sum -c` checks a mirrored copy with no tooling of ours.
    (output_dir / f"{archive.name}.sha256").write_text(
        f"{digest}  {archive.name}\n", encoding="utf-8"
    )
    write_index(
        output_dir / INDEX_FILE,
        package=name,
        version=version,
        file=archive.name,
        sha256=digest,
        size=size,
        meta_file=sidecar_entry(sidecar),
    )
    return Package(path=archive, name=name, version=version, sha256=digest, size=size)


