def assert_glibc_floor(root: Path) -> None:
    """Refuse a package whose binaries need a newer glibc than the baseline.

    Design document §6 sets the floor at glibc 2.28, from the Zephyr SDK
    prebuilt toolchain. A tool that quietly needs a newer one does not fail
    where it is built — it fails on somebody's host, months later, with a
    link error nobody can place. ``objdump`` reads the versioned symbol
    references out of every *host* ELF file in the package; the highest one
    is the floor.

    Skipped, with a notice, when ``objdump`` is not installed: the check is
    worth running wherever it can run, and a missing binutils is not a
    reason to refuse to build a package.
    """
    if shutil.which("objdump") is None:
        print("  objdump not installed — glibc floor not checked", flush=True)
        return
    highest = (0, 0)
    culprit = ""
    for path in root.rglob("*"):
        if not path.is_file() or path.is_symlink():
            continue
        with open(path, "rb") as handle:
            header = handle.read(20)
        if header[:4] != b"\x7fELF" or len(header) < 20:
            continue
        # Only the *host* binaries can raise the host baseline. The Zephyr
        # SDK is mostly target objects — tens of thousands of them — and
        # asking objdump about each would cost minutes to learn that an ARM
        # object references no glibc symbol. ``e_machine`` is two bytes at
        # offset 18, little-endian on both hosts this package is built for:
        # 62 is x86-64, 183 is AArch64.
        if int.from_bytes(header[18:20], "little") not in (62, 183):
            continue
        completed = subprocess.run(
            ["objdump", "-T", str(path)], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL
        )
        # Searched rather than tokenized: objdump prints a symbol's version
        # bare for the default version and in parentheses for every other
        # one — `GLIBC_2.17 fopen` next to `(GLIBC_2.2.5) __register_atfork`
        # — and the parenthesized ones are exactly the older references a
        # floor is made of.
        for major, minor in GLIBC_SYMBOL.findall(completed.stdout.decode("utf-8", "replace")):
            version = (int(major), int(minor))
            if version > highest:
                highest, culprit = version, path.relative_to(root).as_posix()
    print(f"  highest glibc requirement: {highest[0]}.{highest[1]} ({culprit})", flush=True)
    if highest > GLIBC_FLOOR:
        raise SystemExit(
            f"{culprit} needs glibc {highest[0]}.{highest[1]}, above the "
            f"{GLIBC_FLOOR[0]}.{GLIBC_FLOOR[1]} host baseline this package promises"
        )


def unpack_tools(*, arch: str, cache: Path, root: Path) -> None:
    """Every pinned download, verified and unpacked into the package tree."""
    downloads = TOOL_DOWNLOADS[arch]

    sdk_dir = root / f"zephyr-sdk-{ZEPHYR_SDK_VERSION}"
    # The toolchain archive unpacks to `<toolchain>/`, and the SDK expects it
    # under `gnu/` — which is what the SDK's own setup.sh does with it, minus
    # the interactive prompts and the host-tool installer. The SDK's host
    # tools (qemu, openocd, a second dtc) are deliberately not installed.
    archive = fetch(downloads["zephyr-sdk"]["url"], downloads["zephyr-sdk"]["sha256"], cache)
    with tarfile.open(archive, mode="r:xz") as tar:
        tar.extractall(root, filter="tar")
    shutil.rmtree(sdk_dir / "hosttools", ignore_errors=True)
    (sdk_dir / "gnu").mkdir(parents=True, exist_ok=True)
    archive = fetch(
        downloads["zephyr-toolchain"]["url"], downloads["zephyr-toolchain"]["sha256"], cache
    )
    with tarfile.open(archive, mode="r:xz") as tar:
        tar.extractall(sdk_dir / "gnu", filter="tar")

    # gn — one binary in a zip.
    archive = fetch(downloads["gn"]["url"], downloads["gn"]["sha256"], cache)
    (root / "gn").mkdir(parents=True, exist_ok=True)
    shutil.unpack_archive(archive, root / "gn", format="zip")
    (root / "gn" / "gn").chmod(0o755)

    # CMake — the upstream tree, with the version directory flattened away so
    # the entry point does not have to know the version to build a PATH.
    archive = fetch(downloads["cmake"]["url"], downloads["cmake"]["sha256"], cache)
    with tempfile.TemporaryDirectory(dir=root.parent) as staging:
        with tarfile.open(archive, mode="r:gz") as tar:
            tar.extractall(staging, filter="tar")
        (unpacked,) = list(Path(staging).iterdir())
        shutil.move(str(unpacked), str(root / "cmake"))

    # Ninja — one binary in a zip.
    archive = fetch(downloads["ninja"]["url"], downloads["ninja"]["sha256"], cache)
    (root / "ninja").mkdir(parents=True, exist_ok=True)
    shutil.unpack_archive(archive, root / "ninja", format="zip")
    (root / "ninja" / "ninja").chmod(0o755)


def build_wheels(*, source: Path, root: Path, mtime: int, image: str) -> None:
    """Build the complete wheel set the build virtual environment is created from.

    Wheels rather than a ready virtual environment, because a virtual
    environment is not relocatable — absolute interpreter paths, absolute
    shebangs — so provisioning creates it at its final location, offline.
    Everything is built to a wheel here (``pip wheel``) rather than left as
    an sdist: some transitive dependencies ship as sdists by default, and
    building those during provisioning would be fragile on a host with no
    network and no compiler.

    Built in a container, because the interpreter that builds the wheels
    decides which interpreter can install them, and the one the environment
    runs on is :data:`BASE_IMAGE`'s — see there for why the packager image
    supplies it rather than the base itself. ``/usr/bin/python3`` explicitly:
    the packager image puts its own virtual environment first on ``PATH``, and
    a virtual environment inside a virtual environment is not what decides an
    ABI. ``SOURCE_DATE_EPOCH`` is what makes a locally built wheel
    reproducible: without it the zip carries the build time, and the two
    dependencies that arrive as sdists would differ between two package
    builds for no reason.
    """
    wheels = root / "wheels"
    wheels.mkdir(parents=True, exist_ok=True)
    script = "\n".join(
        [
            "/usr/bin/python3 -m venv /tmp/wheelbuild",
            "/tmp/wheelbuild/bin/pip wheel --disable-pip-version-check "
            f"--no-cache-dir -r /src/{REQUIREMENTS_FILE} -w /out",
        ]
    )
    previous = os.environ.get("SOURCE_DATE_EPOCH")
    os.environ["SOURCE_DATE_EPOCH"] = str(mtime)
    try:
        run_in_container(image, {source: "/src", wheels: "/out"}, script, network=True)
    finally:
        if previous is None:
            del os.environ["SOURCE_DATE_EPOCH"]
        else:
            os.environ["SOURCE_DATE_EPOCH"] = previous


def requirement_version(requirements: Path, package: str) -> str:
    """The version *requirements* pins *package* at, or a refusal.

    The environment's own requirement set is the one place its Python
    dependencies are pinned, and the package build reads it out of the
    packaged commit — so the version the meta file reports for ``west`` is
    the version the wheel set actually holds.
    """
    for line in requirements.read_text(encoding="utf-8").splitlines():
        name, separator, version = line.strip().partition("==")
        if separator and name.lower() == package:
            return version
    raise SystemExit(f"{requirements} pins no {package}")


def tools_contents(*, arch: str, os_name: str, python: str, west: str) -> dict:
    """Which tools this package carries, at which versions.

    Everything a build compiles with, in one place a reader can compare
    two packages by: the toolchain and the three build tools are pinned in
    this script, the interpreter is the packager's base — it decides the
    wheel set's ABI and therefore travels with the package — and ``west``
    comes out of the environment's own requirement set.
    """
    return {
        "architecture": f"{os_name}-{arch}",
        "tools": {
            "cmake": CMAKE_VERSION,
            "gn": GN_REVISION,
            "ninja": NINJA_VERSION,
            "python": python,
            "toolchain": ZEPHYR_TOOLCHAIN,
            "west": west,
            "zephyr-sdk": ZEPHYR_SDK_VERSION,
        },
    }


def build_tools_package(
    *,
    repository: Path,
    revision: str,
    output_dir: Path,
    work: Path,
    arch: str,
    os_name: str,
    image: str,
    version_suffix: str | None = None,
):
    """The whole tools package, from pins and a commit to a file."""
    if arch not in TOOL_DOWNLOADS:
        raise SystemExit(f"no downloads pinned for {arch!r}: {sorted(TOOL_DOWNLOADS)}")
    commit = _git(repository, "rev-parse", "--verify", f"{revision}^{{commit}}").decode().strip()
    version = declared_versions(repository, commit, suffix=version_suffix)["tools"]
    mtime = commit_timestamp(repository, commit)
    name = tools_package_name(os_name, arch)

    source = work / "source"
    if source.exists():
        shutil.rmtree(source)
    extract_revision(repository, commit, source, REQUIREMENTS_FILE, ENTRY_SOURCE)

    root = work / "root"
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)

    print("unpacking the pinned tools", flush=True)
    unpack_tools(arch=arch, cache=work / "downloads", root=root)
    print("building the wheel set", flush=True)
    build_wheels(source=source, root=root, mtime=mtime, image=image)

    entry = root / TOOLS_ENTRY
    entry.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source / ENTRY_SOURCE, entry)
    entry.chmod(0o755)

    write_json(
        root / TOOLS_MANIFEST,
        {
            "package": name,
            "version": version,
            "commit": commit,
            "os": os_name,
            "arch": arch,
            "entry-point": TOOLS_ENTRY,
            "zephyr-sdk": ZEPHYR_SDK_VERSION,
            "zephyr-toolchain": ZEPHYR_TOOLCHAIN,
            "cmake": CMAKE_VERSION,
            "ninja": NINJA_VERSION,
            "gn": GN_REVISION,
        },
    )

    architecture = f"{os_name}-{arch}"
    # The family, with the platform said once: the concrete package name
    # is the two of them joined, and stating it twice would let them
    # disagree. `requires` is absent rather than empty — the tools are the
    # end of the chain and constrain nothing below them, which is a
    # different statement from "nothing in particular".
    meta = release_lines.json_bytes(
        release_lines.meta_document(
            name=TOOLS_FAMILY,
            version=version,
            architecture=architecture,
            requires=None,
            inputs=release_lines.inputs_sha256(
                "tools", commit, repository=repository, architecture=architecture
            ),
            contents=tools_contents(
                arch=arch,
                os_name=os_name,
                python=release_lines.packager_python(repository, commit),
                west=requirement_version(source / REQUIREMENTS_FILE, "west"),
            ),
        )
    )

    print("checking the host baseline", flush=True)
    assert_glibc_floor(root)
    print("packing", flush=True)
    return publish(root, output_dir, name=name, version=version, mtime=mtime, meta=meta)


