def materialize_workspace(*, source: Path, work: Path, image: str) -> None:
    """Lay the west workspace out, patch it, fetch its blobs, record it.

    Each step is there for a reason stated at its constant: shallow update,
    tag refs fetched back, patches applied as working-tree changes, blobs
    fetched, the record written, and only then the manifest repository's
    directory emptied — the record needs the manifest to read the workspace,
    and the SDK is mounted per build rather than packaged.

    It runs inside the pinned packager image because the west that lays a
    workspace out and the west that reads it later have to be one version,
    and that image is where the pinned one lives.
    """
    workspace = work / WORKSPACE_DIR
    (workspace / MANIFEST_DIR).mkdir(parents=True, exist_ok=True)
    shutil.copy2(source / "west.yml", workspace / MANIFEST_DIR / "west.yml")

    steps = [
        f"cd /work/{WORKSPACE_DIR}",
        # `west init -l` needs exactly one file of the manifest repository:
        # west.yml. It never asks whether the directory is a git repository,
        # which is what makes it possible to lay a workspace out from a bare
        # copy of the manifest and deliver the real SDK into it later.
        f"west init -l {MANIFEST_DIR}",
        # Deliberately without a group-filter: the `matter` group is wanted
        # here — this is the environment that builds Matter firmware.
        "west update --narrow -o=--depth=1",
    ]
    for project, (path, _layer) in PROJECTS.items():
        # The remote is asked for rather than named: west calls it after the
        # manifest's `remotes:` entry, never `origin`, and each project has
        # exactly one — so taking the first is both correct and indifferent
        # to what it is called.
        steps.append(
            f'revision="$(west list -f "{{revision}}" {project})"; '
            f'remote="$(git -C {path} remote | head -n1)"; '
            f'test -n "$remote"; '
            f'git -C {path} fetch --depth=1 "$remote" '
            f'"refs/tags/$revision:refs/tags/$revision"'
        )
    for project, (path, _layer) in PROJECTS.items():
        # The patch set, applied the way patches/README.md documents it:
        # `git apply`, nothing else — no --3way, no --reject, no retry. A
        # patch that has drifted from the revision west.yml pins fails the
        # package build, loudly, right here.
        #
        # Left as working-tree changes, NOT committed: committing moves
        # `git describe` from the tag to `<tag>-1-g<sha>` and therefore
        # changes BUILD_VERSION, the banner and the firmware.
        steps.append(
            f"for patch in /src/patches/{project}-*.patch; do "
            f'git -C {path} apply --verbose "$patch"; done'
        )
    # The binary blobs west deliberately does not fetch with the sources. A
    # build with no network cannot fetch them later, so the package carries
    # them or the module is unusable.
    steps += [f"west blobs fetch {module}" for module in BLOB_MODULES]
    # Pre-populated so no lazy configuration write ever happens on a
    # read-only tree: west's zephyr extension writes zephyr.base on first
    # use, and in a frozen store there is nowhere to write it.
    steps.append("west config zephyr.base zephyr")

    run_in_container(image, {work: "/work", source: "/src"}, "\n".join(steps), network=True)


def record_workspace(*, source: Path, work: Path, image: str) -> None:
    """Write the workspace record, then empty the manifest repository's directory.

    One implementation of that document exists —
    ``packaging/build-environment/workspace-record.py``, which is packaging
    material rather than image content. It has to run before the manifest
    repository's directory is emptied, because it reads the workspace
    through west.
    """
    patch_arguments: list[str] = []
    for project, (_path, layer) in PROJECTS.items():
        for patch in sorted((source / "patches").glob(f"{project}-*.patch")):
            patch_arguments += ["--patch", f"{layer}=/src/patches/{patch.name}"]

    script = "\n".join(
        [
            "python3 /src/packaging/build-environment/workspace-record.py "
            f"--topdir /work/{WORKSPACE_DIR} --output /work/{RECORD_FILE} "
            f"--clone {CLONE_KIND} " + " ".join(patch_arguments),
            # The manifest repository's directory is emptied and left in
            # place. west needed west.yml to get here; the orchestrator
            # brings the SDK back at run time, because it is a hash-pinned
            # package chosen per build rather than environment content.
            f"rm -rf /work/{WORKSPACE_DIR}/{MANIFEST_DIR}",
            f"mkdir /work/{WORKSPACE_DIR}/{MANIFEST_DIR}",
        ]
    )
    run_in_container(image, {work: "/work", source: "/src"}, script, network=False)


def pregen_chip_root() -> str:
    """Where a consumer is told the pre-generated code is.

    CHIP's CMake glue indexes the pre-generation directory by the path of the
    data-model file **relative to CHIP_ROOT**
    (``build/chip/chip_codegen.cmake``): it computes
    ``${CHIP_CODEGEN_PREGEN_DIR}/${relative path without extension}/codegen/<generator>``
    and the same with ``/zap/``. Our data model lives in the SDK, outside
    CHIP, so that relative path climbs out of the CHIP tree and back down
    into the manifest repository's directory.

    So the pre-generation directory is laid out as a **shadow of the
    workspace**, and the consumer is handed the shadow's CHIP root. Then
    "relative to CHIP_ROOT" means the same thing in the shadow as in the
    workspace, and nothing has to agree about how deep anything is.

    The shadow's CHIP root is an **empty directory** the package carries on
    purpose. The path a compiler is handed keeps the ``..`` in it, and the
    kernel resolves ``..`` by walking, not by rewriting the string: every
    component in front of it has to exist or the whole path is ENOENT.
    Measured — without the empty directory the include path resolves to
    nothing and the first CHIP header out of the pre-generated tree is not
    found.
    """
    return f"{PREGEN_DIR}/{CHIP_PATH}"


def pregenerate_matter(*, source: Path, work: Path, image: str) -> None:
    """Generate the Matter data-model code the build would otherwise make itself.

    Two generators, because a Matter application build asks for two
    (``src/app/chip_data_model.cmake``):

    ``codegen/cpp-app``
        from the ``.matter`` IDL, by ``scripts/codegen.py`` — pure Python.
    ``zap/app-templates``
        from the ``.zap``, by ``scripts/tools/zap/generate.py`` — the one
        step that needs the ``zap`` tool, and the reason this happens here:
        zap is distributed only as an Electron application and needs a
        desktop shared-library set no lean host baseline should carry.
        MCUHome's input is a single static root-node configuration that
        changes only with a release, so its output is a release constant.

    They are invoked directly rather than through ``scripts/codepregen.py``.
    codepregen walks a root and derives its output paths from *that* root,
    which does not agree with what the consumer computes for a data model
    outside CHIP; and its ZAP target passes no ``--zcl``, which an
    out-of-tree ``.zap`` needs, because the path stored inside the file is
    relative to CHIP's own example directories
    (``components/matter/zap/README.md``). The two invocations below are the
    ones that README documents, pointed at the exact directories the build
    reads.
    """
    workspace = f"/work/{WORKSPACE_DIR}"
    chip = f"{workspace}/{CHIP_PATH}"
    # The path of the data model relative to CHIP_ROOT, spelled out in the
    # shadow: <pregen>/<manifest dir>/<zap stem>. See pregen_chip_root().
    shadow = f"/work/{PREGEN_DIR}/{MANIFEST_DIR}/{ZAP_STEM}"

    script = "\n".join(
        [
            f"mkdir -p {shadow}/codegen/cpp-app {shadow}/zap/app-templates/zap-generated "
            f"/work/{pregen_chip_root()}",
            # scripts/pyshim/ stands in for CHIP's `python_path` helper, which
            # the v1.5.1.0 release tarball ships without and its codegen
            # imports.
            "export PYTHONPATH=/src/scripts/pyshim",
            # The .matter IDL half. --generator cpp-app is what
            # chip_configure_data_model() asks chip_codegen() for.
            f"python3 {chip}/scripts/codegen.py --generator cpp-app "
            f"--output-dir {shadow}/codegen/cpp-app "
            f"/src/{ZAP_STEM}.matter",
            # The .zap half. --zcl is required: the path stored inside the
            # .zap is relative to CHIP's own example directories and does not
            # resolve from here — the build passes the same path via
            # chip_configure_data_model(... ZCL_PATH ...) for that reason.
            f"python3 {chip}/scripts/tools/zap/generate.py /src/{ZAP_STEM}.zap "
            f"--templates {chip}/src/app/zap-templates/app-templates.json "
            f"--zcl {chip}/src/app/zap-templates/zcl/zcl.json "
            f"--no-prettify-output -o {shadow}/zap/app-templates/zap-generated",
        ]
    )
    run_in_container(image, {work: "/work", source: "/src"}, script, network=False)


def prune(root: Path) -> None:
    """Remove what the package build left behind and no build reads.

    Laying the workspace out and pre-generating the Matter code runs Python
    out of the source trees, and Python writes a ``__pycache__`` beside
    every module it imports. Those files are not part of the workspace
    ``west.yml`` describes; they are byproducts of *this* build, they carry
    the source file's timestamp and size in their header, and a read-only
    store cannot use them anyway — CPython simply skips the cache it cannot
    write. Shipping them would put a few megabytes of nothing into the
    package and make two builds of one revision differ for a reason that has
    no relation to the revision.
    """
    for path in sorted(root.rglob(PRUNED_DIR), reverse=True):
        if path.is_dir():
            shutil.rmtree(path)


def applied_patches(source: Path) -> list[str]:
    """The patch files this package build applies, in the order it applies them.

    The names alone, because that is what a reader of the meta file wants
    to know ("which patches are in here"); the record inside the package
    identifies each one by its SHA-256 as well, which is the identity
    ``patches/README.md`` makes necessary — a patch is regenerated in
    place, keeping its file name.
    """
    return [
        patch.name
        for project in PROJECTS
        for patch in sorted((source / "patches").glob(f"{project}-*.patch"))
    ]


def workspace_contents(*, record: dict, patches: list[str], document: dict[str, str]) -> dict:
    """What the workspace package resolved to, for its meta file.

    Three answers, and each of them is a question somebody has had to ask
    a package by unpacking it:

    ``projects``
        Every west project the workspace carries — the manifest's own and
        every one imported through it — with the revision the manifest
        pins and the commit that revision resolved to. Two of those pins
        are *tags*, and a tag is movable at the remote, so "which bytes"
        and "which pin" are different facts and both are stated.
    ``patches``
        Which patch files were applied on top.
    ``environment``
        The §5 declaration this package carries, repeated here so that a
        reader of the meta file sees the package set an image assembles
        from it without opening the archive.
    """
    projects = record.get("projects", {})
    return {
        "environment": dict(document),
        "patches": patches,
        "projects": {
            name: {
                "path": project["path"],
                "pinned": project["revision"],
                "revision": project["commit"],
                "url": project["url"],
            }
            for name, project in sorted(projects.items())
        },
    }


def build_workspace_package(
    *,
    repository: Path,
    revision: str,
    output_dir: Path,
    work: Path,
    image: str,
    version_suffix: str | None = None,
):
    """The whole workspace package, from a commit to a file."""
    commit = _git(repository, "rev-parse", "--verify", f"{revision}^{{commit}}").decode().strip()
    versions = declared_versions(repository, commit, suffix=version_suffix)
    version = versions["workspace"]
    mtime = commit_timestamp(repository, commit)

    source = work / "source"
    if source.exists():
        shutil.rmtree(source)
    extract_revision(
        repository,
        commit,
        source,
        "west.yml",
        "patches",
        "scripts/pyshim",
        "packaging/build-environment/workspace-record.py",
        f"{ZAP_STEM}.zap",
        f"{ZAP_STEM}.matter",
    )

    root = work / "root"
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)

    print("materializing the west workspace", flush=True)
    materialize_workspace(source=source, work=root, image=image)
    print("recording the workspace", flush=True)
    record_workspace(source=source, work=root, image=image)
    print("pre-generating the Matter data model", flush=True)
    pregenerate_matter(source=source, work=root, image=image)
    prune(root)

    document = declaration(
        zephyr=zephyr_version(repository, commit),
        workspace_version=version,
        tools_version=versions["tools"],
    )
    meta = release_lines.json_bytes(
        release_lines.meta_document(
            name=WORKSPACE_PACKAGE,
            version=version,
            architecture=None,
            requires=release_lines.requires_of(
                release_lines.environment(repository, commit), "workspace"
            ),
            inputs=release_lines.inputs_sha256("workspace", commit, repository=repository),
            contents=workspace_contents(
                record=json.loads((root / RECORD_FILE).read_text(encoding="utf-8")),
                patches=applied_patches(source),
                document=document,
            ),
        )
    )
    # Where the parts of this package are, said by the package rather than
    # guessed by whoever unpacks it. `matter-pregen-chip-root` is the value
    # a build passes as CHIP_CODEGEN_PREGEN_DIR (see pregen_chip_root).
    write_json(
        root / "build-workspace.json",
        {
            "package": WORKSPACE_PACKAGE,
            "version": version,
            "commit": commit,
            "workspace": WORKSPACE_DIR,
            "workspace-record": RECORD_FILE,
            "manifest-directory": f"{WORKSPACE_DIR}/{MANIFEST_DIR}",
            "matter-pregen-chip-root": pregen_chip_root(),
        },
    )

    print("packing", flush=True)
    return publish_workspace(
        root, output_dir, version=version, mtime=mtime, document=document, meta=meta
    )


def publish_workspace(
    root: Path,
    output_dir: Path,
    *,
    version: str,
    mtime: int,
    document: dict[str, str],
    meta: bytes,
) -> Package:
    """Pack the workspace package with the §5 declaration at the top of it.

    One function rather than two calls at the call site, because the
    declaration has to be written before the archive is packed and only
    the workspace package carries one: it is the architecture-neutral
    member of the set, and a set that spans architectures needs a carrier
    that does not.

    The declaration and the meta file are two documents and stay two: the
    declaration is what the *specification* asks a build environment for
    and what an image mirrors into its labels, the meta file is what
    MCUHome's own release chain asks a *package* for. Their audiences
    differ, and so does what they may contain — which is also why only one
    of them is published beside the archive.
    """
    write_json(root / DECLARATION_FILE, document)
    return publish(
        root, output_dir, name=WORKSPACE_PACKAGE, version=version, mtime=mtime, meta=meta
    )


