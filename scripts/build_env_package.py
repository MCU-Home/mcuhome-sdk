def run_in_container(image: str, mounts: dict[Path, str], script: str, *, network: bool) -> None:
    """Run *script* with ``/bin/sh`` inside *image*, as the calling user.

    As the calling user (``--user``) so that everything it writes into the
    mounts belongs to whoever is building the package and not to root — a
    package build must not need a privileged cleanup afterwards. ``HOME`` is
    pointed at a writable directory because that user has no entry in the
    image's ``/etc/passwd`` and several tools insist on having one.
    """
    command = ["docker", "run", "--rm", "--user", f"{os.getuid()}:{os.getgid()}"]
    if not network:
        command += ["--network", "none"]
    for source, destination in mounts.items():
        command += ["--volume", f"{source}:{destination}"]
    command += ["--env", "HOME=/tmp"]
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    if epoch:
        command += ["--env", f"SOURCE_DATE_EPOCH={epoch}"]
    command += [image, "/bin/sh", "-euc", script]
    subprocess.run(command, check=True)


def packager_image(override: str | None = None) -> str:
    """The packager image to run in, from the one place that names it.

    *override* is what ``--packager-image`` was given, and exists for the
    two occasions on which the pinned reference cannot be used: publishing
    the packager for the first time, when no digest exists yet, and trying
    a change to ``containers/build-environment-packager/`` before it is
    published. A package built with an override is not a package anybody
    else can reproduce, which is why it is a deliberate flag and never a
    fallback.
    """
    if override:
        return override
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from packager_image import reference  # noqa: PLC0415 - repo-relative import

    return reference()


